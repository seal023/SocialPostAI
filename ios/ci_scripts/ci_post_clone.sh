#!/bin/sh
set -e

echo "[ci_post_clone] Repository: $CI_PRIMARY_REPOSITORY_PATH"
echo "[ci_post_clone] Branch: ${CI_BRANCH:-unknown}"
echo "[ci_post_clone] Build: ${CI_BUILD_NUMBER:-unknown}"

cd "$CI_PRIMARY_REPOSITORY_PATH"

export EXPO_NO_TELEMETRY=1
export CI=1

# ── Node.js ────────────────────────────────────────────────────────────────
if ! command -v node > /dev/null 2>&1; then
  for nvm_node in \
    "/Users/local/.nvm/versions/node/$(ls /Users/local/.nvm/versions/node 2>/dev/null | sort -V | tail -1)/bin" \
    "/opt/homebrew/bin" \
    "/usr/local/bin"; do
    if [ -x "$nvm_node/node" ]; then
      export PATH="$nvm_node:$PATH"
      break
    fi
  done
fi

if ! command -v node > /dev/null 2>&1; then
  echo "[ci_post_clone] node not found — installing via Homebrew..."
  brew install node@22
  export PATH="/opt/homebrew/opt/node@22/bin:$PATH"
fi

echo "[ci_post_clone] node: $(node -v)"
export NODE_BINARY=$(command -v node)

# ── npm ────────────────────────────────────────────────────────────────────
if [ -f package-lock.json ]; then
  npm ci
else
  npm install
fi
echo "[ci_post_clone] npm deps installed"

# ── Expo prebuild: generate the native iOS project ─────────────────────────
# Back up ci_scripts — expo prebuild may regenerate ios/; restore it afterwards
# so Xcode Cloud keeps finding the CI scripts.
cp -R ios/ci_scripts /tmp/ci_scripts_backup 2>/dev/null || true

echo "[ci_post_clone] Running expo prebuild (ios)..."
./node_modules/.bin/expo prebuild --platform ios --no-install
echo "[ci_post_clone] prebuild complete"

if [ ! -d ios/ci_scripts ]; then
  echo "[ci_post_clone] Restoring ci_scripts..."
  cp -R /tmp/ci_scripts_backup ios/ci_scripts
fi

# Detect generated project name dynamically (no hardcoding — survives renames).
PROJECT_NAME=$(ls ios/*.xcodeproj 2>/dev/null | head -n1 | sed 's#^ios/##; s#\.xcodeproj$##')
if [ -z "$PROJECT_NAME" ]; then
  echo "[ci_post_clone] ERROR: no .xcodeproj generated by prebuild"
  exit 1
fi
echo "[ci_post_clone] Project name: $PROJECT_NAME"

# Write build number early (ci_pre_xcodebuild's agvtool also covers this).
PBXPROJ="ios/${PROJECT_NAME}.xcodeproj/project.pbxproj"
if [ -n "${CI_BUILD_NUMBER:-}" ] && [ -f "$PBXPROJ" ]; then
  sed -i.bak -E "s/(CURRENT_PROJECT_VERSION = )[0-9]+;/\1${CI_BUILD_NUMBER};/g" "$PBXPROJ"
  rm -f "${PBXPROJ}.bak"
  echo "[ci_post_clone] CURRENT_PROJECT_VERSION = $CI_BUILD_NUMBER"
fi

# ── CocoaPods ──────────────────────────────────────────────────────────────
if ! command -v pod > /dev/null 2>&1; then
  gem install --user-install cocoapods
  export PATH="$HOME/.gem/bin:$PATH"
fi

cd ios
export NODE_BINARY="$NODE_BINARY"
COCOAPODS_DISABLE_STATS=1 pod install --repo-update
echo "[ci_post_clone] pod install complete"

# ── Patch fmt 11.x consteval (Apple Clang 15+ / Xcode 15+) ────────────────
for FMT_HEADER in \
  "Pods/fmt/include/fmt/base.h" \
  "Pods/fmt/include/fmt/core.h" \
  "Pods/fmt/include/fmt/format.h"; do
  if [ -f "$FMT_HEADER" ]; then
    sed -i.bak 's/#  define FMT_USE_CONSTEVAL 1/#  define FMT_USE_CONSTEVAL 0/g' "$FMT_HEADER"
    sed -i.bak 's/#define FMT_USE_CONSTEVAL 1/#define FMT_USE_CONSTEVAL 0/g' "$FMT_HEADER"
    rm -f "${FMT_HEADER}.bak"
  fi
done

cp Podfile.lock Pods/Manifest.lock

PODS_XCCONFIG="Pods/Target Support Files/Pods-${PROJECT_NAME}/Pods-${PROJECT_NAME}.release.xcconfig"
if [ ! -f "$PODS_XCCONFIG" ]; then
  echo "[ci_post_clone] ERROR: $PODS_XCCONFIG not found after pod install"
  exit 1
fi

echo "[ci_post_clone] Done"
